//! Manual Japanese Font Embedding Example
//!
//! This example demonstrates creating a Japanese PDF by manually embedding a Japanese font.
//! This is the current workaround until font selection from font-family is implemented.

use fop_render::PdfDocument;
use fop_render::pdf::document::PdfPage;
use fop_types::Length;
use std::fs;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("Creating Japanese PDF with manual font embedding...\n");

    // Try to load a Japanese font from common system locations
    let japanese_font_paths = vec![
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/truetype/umefont_670/ume-pgs4.ttf",
        "/usr/share/fonts/truetype/takao-gothic/TakaoPGothic.ttf",
        "/System/Library/Fonts/Hiragino Sans GB.ttc", // macOS
    ];

    let mut font_data = None;
    let mut font_source = String::new();

    for path in &japanese_font_paths {
        if let Ok(data) = fs::read(path) {
            println!("✓ Found Japanese font: {}", path);
            font_source = path.to_string();
            font_data = Some(data);
            break;
        }
    }

    let font_data = font_data.ok_or(
        "No Japanese font found. Please install:\n\
         - Linux: sudo apt install fonts-noto-cjk\n\
         - macOS: (pre-installed)\n\
         - Windows: Download Noto Sans CJK from Google Fonts"
    )?;

    // Create PDF document
    let mut pdf = PdfDocument::new();

    // Set document metadata
    pdf.info.title = Some("Japanese PDF Example".to_string());
    pdf.info.author = Some("Apache FOP Rust".to_string());

    // Embed the Japanese font
    println!("Embedding font...");
    let font_index = pdf.embed_font(font_data)?;
    println!("✓ Font embedded (index: {})", font_index);

    // Create A4 page (210mm x 297mm)
    let mut page = PdfPage::new(Length::from_mm(210.0), Length::from_mm(297.0));

    // Add Japanese content
    println!("\nAdding Japanese text...");

    let y_start = Length::from_mm(280.0); // Start near top of page
    let x_margin = Length::from_mm(20.0);
    let line_height = Length::from_pt(20.0);

    // Title
    let title_text = "請求書";
    pdf.font_manager.record_text(font_index, title_text);
    page.add_text_with_font(
        title_text,
        x_margin,
        y_start,
        Length::from_pt(24.0),
        font_index,
    );

    // Subtitle
    let subtitle_text = "株式会社サンプル 御中";
    pdf.font_manager.record_text(font_index, subtitle_text);
    page.add_text_with_font(
        subtitle_text,
        x_margin,
        y_start - line_height * 2,
        Length::from_pt(14.0),
        font_index,
    );

    // Content lines
    let content_lines = vec![
        "発行日: 2026年2月16日",
        "",
        "商品明細:",
        "  1. ソフトウェアライセンス ......... ¥500,000",
        "  2. 技術サポート(1年間) ........... ¥100,000",
        "  3. 導入支援サービス ............... ¥100,000",
        "",
        "小計: ¥700,000",
        "消費税(10%): ¥70,000",
        "合計: ¥770,000",
        "",
        "お支払期限: 2026年3月31日まで",
        "",
        "こんにちは、世界！",
        "This demonstrates mixing Japanese and English text.",
    ];

    let mut y = y_start - line_height * 4;
    for line in &content_lines {
        pdf.font_manager.record_text(font_index, line);
        page.add_text_with_font(
            line,
            x_margin,
            y,
            Length::from_pt(12.0),
            font_index,
        );
        y -= Length::from_pt(14.0);
    }

    // Add footer
    let footer_text = "Generated by Apache FOP Rust - Unicode Support";
    pdf.font_manager.record_text(font_index, footer_text);
    page.add_text_with_font(
        footer_text,
        x_margin,
        Length::from_mm(10.0),
        Length::from_pt(10.0),
        font_index,
    );

    // Add page to document
    pdf.add_page(page);

    // Generate PDF
    println!("\nGenerating PDF...");
    let pdf_bytes = pdf.to_bytes()?;

    // Save to file
    let output_path = "/tmp/japanese_manual_font.pdf";
    fs::write(output_path, &pdf_bytes)?;

    println!("✓ PDF created: {} ({} KB)", output_path, pdf_bytes.len() / 1024);
    println!("\nFont source: {}", font_source);
    println!("\n✅ SUCCESS! Japanese characters should render correctly in the PDF.");
    println!("   Open the PDF to verify: {}", output_path);

    Ok(())
}
